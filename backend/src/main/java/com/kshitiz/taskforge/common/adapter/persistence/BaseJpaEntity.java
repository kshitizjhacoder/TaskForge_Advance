package com.kshitiz.taskforge.common.adapter.persistence;

import jakarta.persistence.Column;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.Version;
import lombok.Getter;
import lombok.Setter;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.time.Instant;
import java.util.UUID;

/**
 * Columns shared by every main database table: UUID primary key, audit timestamps and an
 * optimistic-locking version.
 *
 * <ul>
 *   <li>{@code id} is generated by the domain object (not the database), so it is known
 *       before saving.</li>
 *   <li>{@code createdAt}/{@code updatedAt} are filled automatically by Spring Data auditing
 *       (enabled in {@code JpaConfig}).</li>
 *   <li>{@code version} is increased on every update. If two users edit the same row at the
 *       same time, the second save fails instead of silently overwriting the first. A
 *       {@code null} version also tells Spring Data the row is new (INSERT, not UPDATE).</li>
 * </ul>
 */
@Getter
@Setter
@MappedSuperclass
@EntityListeners(AuditingEntityListener.class)
public abstract class BaseJpaEntity {

    @Id
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @LastModifiedDate
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    @Version
    @Column(name = "version", nullable = false)
    private Long version;
}
